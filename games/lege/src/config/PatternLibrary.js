// 牌桌图案库：每个图案是一个"形状遮罩" inside(u, v)，u/v ∈ [-1, 1] 为牌桌归一化坐标 (v 向下)。
// LayoutGenerator 会按关卡的 mode (错位方式) 与 shrink (逐层收缩) 在遮罩里摆放卡牌。
//
// 新增图案只需两种写法之一：
//   1) 数学函数：  myShape: { name: '名字', inside: (u, v) => 布尔 }
//   2) ASCII 图：  myShape: { name: '名字', ascii: ['..##..', ...] }  ('#' = 形状内，任意宽高，自动拉伸到牌桌)
// fill：一张卡的 4 个采样点中至少几个落在形状内才放置 (默认 3，越小形状越"胖")

function fromAscii(rows) {
  const h = rows.length;
  const w = rows[0].length;
  return (u, v) => {
    const c = Math.floor(((u + 1) / 2) * w);
    const r = Math.floor(((v + 1) / 2) * h);
    if (r < 0 || r >= h || c < 0 || c >= w) return false;
    return rows[r][c] === '#';
  };
}

function pointInPoly(x, y, pts) {
  let inside = false;
  for (let i = 0, j = pts.length - 1; i < pts.length; j = i++) {
    const [xi, yi] = pts[i]; const [xj, yj] = pts[j];
    if ((yi > y) !== (yj > y) && x < ((xj - xi) * (y - yi)) / (yj - yi) + xi) inside = !inside;
  }
  return inside;
}

const STAR_PTS = Array.from({ length: 10 }, (_, i) => {
  const r = i % 2 === 0 ? 1.12 : 0.56;
  const a = -Math.PI / 2 + (i * Math.PI) / 5;
  return [Math.cos(a) * r, Math.sin(a) * r + 0.1];
});

