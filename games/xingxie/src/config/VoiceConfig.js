// 展开成 { [speaker]: { [group]: [{file,text,zh,tts,emo,voice}] } }
export const VOICE_LINES = {};
for (const [who, groups] of Object.entries(LINES)) {
  const cast = VOICE_CAST[who];
  VOICE_LINES[who] = {};
  for (const [group, list] of Object.entries(groups)) {
    VOICE_LINES[who][group] = list.map((l, i) => {
      const { emo, text, zh, tts, ...o } = l;
      const e = EMOTIONS[emo];
      const [style, styleId] = cast.styles[emo] || Object.values(cast.styles)[0];
      return { file: `assets/audio/voice/${who}_${group}_${i + 1}.mp3`, text, zh, tts, emo,
        voice: { ...e, styleId, style, speaker: cast.speaker, speed: +Math.min(1.22, Math.max(1.13, e.speed * cast.speedMul)).toFixed(3), pitch: e.pitch + cast.pitch, ...o } };
    });
  }
}

